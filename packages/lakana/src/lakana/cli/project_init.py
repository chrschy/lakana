"""Relative path → template; `{repo}` and `{version}` are substituted with `str.format`."""


def _is_dev_build(version: str) -> bool:
    """Report whether `version` is a development or local build no index will have.

    Parameters
    ----------
    version
        The CLI's version string.

    Returns
    -------
    bool
        `True` for ``.dev`` releases and local versions (``+...``, ``0+unknown``).
    """
    return ".dev" in version or "+" in version


def _git_lacks_identity(directory: Path) -> bool:
    """Report whether `git commit` in `directory` would fail for want of a name or email.

    Asks git itself (`git var`), so config files, environment variables and its own
    guessing are all taken into account exactly as a commit would.

    Parameters
    ----------
    directory
        Where the project was written.

    Returns
    -------
    bool
        `True` only when git ran and could not resolve an author or committer identity;
        `False` when it has one, and when git is missing or cannot be run.
    """
    for variable in ("GIT_AUTHOR_IDENT", "GIT_COMMITTER_IDENT"):
        try:
            result = subprocess.run(  # nosec B603 B607 -- fixed argv
                ["git", "var", variable],
                cwd=directory,
                capture_output=True,
                check=False,
                timeout=3,
            )
        except (OSError, subprocess.SubprocessError):
            return False
        if result.returncode != 0:
            return True
    return False


def write_project(directory: Path, repo: str) -> list[Path]:
    """Write every template into `directory`, refusing to overwrite anything.

    Parameters
    ----------
    directory
        The project directory; created if missing.
    repo
        The repository name for `lakana.yaml` and `pyproject.toml`.

    Returns
    -------
    list of Path
        The files written.

    Raises
    ------
    CliError
        Exit 2 if any target exists or a parent is
        not a directory (nothing is written); exit 3 on a filesystem error
        (files already written are removed).
    """
    targets = {directory / relative: text for relative, text in TEMPLATES.items()}
    existing = [str(path) for path in targets if os.path.lexists(path)]
    if existing:
        raise CliError(f"Refusing to overwrite: {', '.join(existing)}")
    parents = {directory} | {
        directory / parent
        for relative in TEMPLATES
        for parent in Path(relative).parents
        if parent.name
    }
    for parent in sorted(parents):
        if os.path.lexists(parent) and not parent.is_dir():
            raise CliError(
                f"Can't write the project into {directory}: {parent} is not a directory", 3
            )
    written: list[Path] = []
    try:
        for path, text in targets.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("x") as handle:
                handle.write(text.format(repo=repo, version=__version__))
            written.append(path)
    except OSError as exc:
        for path in written:
            path.unlink(missing_ok=True)
        raise CliError(f"Can't write the project into {directory}: {exc}", 3) from exc
    return written


def init(
    directory: Annotated[Path, typer.Argument(help="Project directory (default: here).")] = Path(),
    repo: Annotated[
        str | None, typer.Option("--repo", help="Repository name (default: the directory name).")
    ] = None,
) -> None:
    """Create a Lakana project that deploys unchanged.

    Parameters
    ----------
    directory
        Where to write it.
    repo
        The repository name.

    Raises
    ------
    CliError
        If the name is not a valid repository name (exit 2).
    """
    target = directory.resolve()
    name = repo or target.name
    if not _NAME.match(name):
        raise CliError(
            f"{name!r} is not a valid repository name (letters, digits, '-' and '_'); pass --repo"
        )
    write_project(target, name)
    lines = [
        f"Created a Lakana project in {target}.",
        "Next:",
        f"  cd {shlex.quote(str(target))}",
        "  git init && git add -A && git commit -m 'Initial project'",
        f"  lakana repo add {name} --kind local --url {shlex.quote(str(target))}",
        "  lakana deploy --env dev",
        "  lakana run --env dev",
        "Local repositories must lie under LAKANA_REPO_ROOTS "
        "(local mode allows your home directory).",
    ]
    if _git_lacks_identity(target):
        lines.append(
            "If 'git commit' says it does not know who you are, set a name and email first: "
            "git config --global user.name 'Your Name' && "
            "git config --global user.email you@example.com"
        )
    if _is_dev_build(__version__):
        lines.append(
            f"Note: lakana {__version__} is a development build, so the CI install "
            f"`lakana=={__version__}` can't be installed from PyPI. Ignore this until "
            "you use CI; then edit the pinned version in .github/workflows/lakana-deploy.yml "
            "and .gitlab-ci.yml, or set LAKANA_INDEX_URL to an index that has it."
        )
    typer.echo("\n".join(lines))


def register(app: typer.Typer) -> None:
    """Add `init` to the root app.

    Parameters
    ----------
    app
        The root app.
    """
    app.command("init")(init)
